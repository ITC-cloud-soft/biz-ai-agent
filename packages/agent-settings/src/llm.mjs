// The model clients of the business side: chat (knowledge-graph extraction) and embeddings (RAG), for OpenAI-compatible endpoints
// and Azure OpenAI deployments; the connection test; the DSH overlay for the AI plane's conversation model.
// Errors carry a code only — never the key, never the endpoint's answer body (it may echo the input).
import { httpEmbedder } from '@dsh-bridge/knowledge'

export const AZURE_API_VERSION = '2024-10-21'
const TIMEOUT_MS = 60_000

export class LlmError extends Error {
  constructor(code) { super(code); this.code = code }
}

export function endpointOf(cfg, path) {
  if (!cfg?.baseUrl || !cfg?.model) throw new LlmError('not_configured')
  const base = cfg.baseUrl.replace(/\/+$/, '')
  if (cfg.kind === 'azure-openai') return `${base}/openai/deployments/${encodeURIComponent(cfg.model)}/${path}?api-version=${AZURE_API_VERSION}`
  return `${base}/${path}`
}
export const headersOf = (cfg, key) => (cfg.kind === 'azure-openai' ? { 'api-key': key } : { authorization: `Bearer ${key}` })

/** A chat call that must answer one JSON object (response_format json_object; ```json fences tolerated). */
export function createChat(cfg, key, { fetch: fetchImpl = globalThis.fetch, timeoutMs = TIMEOUT_MS } = {}) {
  if (!key) throw new LlmError('no_key')
  const url = endpointOf(cfg, 'chat/completions')
  return {
    model: cfg.model,
    async json(messages) {
      let res
      try {
        res = await fetchImpl(url, {
          method: 'POST',
          headers: { 'content-type': 'application/json', ...headersOf(cfg, key) },
          body: JSON.stringify({ ...(cfg.kind === 'azure-openai' ? {} : { model: cfg.model }), messages, temperature: 0, response_format: { type: 'json_object' } }),
          signal: AbortSignal.timeout(timeoutMs),
        })
      } catch (error) {
        throw new LlmError(error?.name === 'TimeoutError' ? 'timeout' : 'unreachable')
      }
      if (!res.ok) throw new LlmError(`http_${res.status}`)
      const body = await res.json().catch(() => null)
      const text = body?.choices?.[0]?.message?.content
      if (typeof text !== 'string') throw new LlmError('bad_answer')
      try {
        return JSON.parse(text.replace(/^\s*```(?:json)?\s*|\s*```\s*$/g, ''))
      } catch {
        throw new LlmError('bad_answer')
      }
    },
  }
}

export function createEmbedder(cfg, key, { fetch } = {}) {
  if (!key) throw new LlmError('no_key')
  return httpEmbedder({
    url: endpointOf(cfg, 'embeddings'),
    model: cfg.kind === 'azure-openai' ? undefined : cfg.model,
    headers: headersOf(cfg, key),
    dimensions: cfg.dimensions ?? undefined,
    id: `${cfg.kind}:${cfg.model}${cfg.dimensions ? `:${cfg.dimensions}` : ''}`,
    ...(fetch ? { fetch } : {}),
  })
}

/** The connection test: { ok, ms, error? } — a code, never a body. */
export async function testConnection(target, cfg, key, { fetch } = {}) {
  const t0 = Date.now()
  try {
    if (target === 'embedding') {
      const [v] = await createEmbedder(cfg, key, { fetch }).embed(['connection test'])
      if (!Array.isArray(v) || !v.length) throw new LlmError('bad_answer')
      return { ok: true, ms: Date.now() - t0, dimensions: v.length }
    }
    const r = await createChat(cfg, key, { fetch, timeoutMs: 20_000 }).json([
      { role: 'system', content: 'Answer with the JSON object {"ok": true} and nothing else.' },
      { role: 'user', content: 'connection test' },
    ])
    if (r?.ok !== true) throw new LlmError('bad_answer')
    return { ok: true, ms: Date.now() - t0 }
  } catch (error) {
    const code = error instanceof LlmError ? error.code : /answered (\d{3})/.exec(error?.message ?? '')?.[1] ? `http_${/answered (\d{3})/.exec(error.message)[1]}` : 'failed'
    return { ok: false, ms: Date.now() - t0, error: code }
  }
}

/**
 * The AI plane's conversation model as a DSH --patch overlay (llm-pi-ai provider + agent-default-model). The key appears only as
 * the NAME of an environment variable (apiKeyEnv); a key stored on the settings screen is not usable by DSH.
 */
export function dshOverlay(base) {
  if (!base?.baseUrl || !base?.model) return '# the base model is not configured yet\n'
  const env = base.apiKeyEnv || 'BIZ_AI_AGENT_LLM_KEY'
  const baseURL = base.kind === 'azure-openai' ? `${base.baseUrl}/openai/deployments/${base.model}` : base.baseUrl
  return [
    '# AI plane (DSH) conversation model, generated by the biz-ai-agent settings screen. Apply with dsh --patch <this file>',
    `# or merge it into the product profile. ${env} must be set in the DSH environment (never write the key here).`,
    '- id: llm-pi-ai',
    '  config:',
    '    providers:',
    '      biz-ai-agent:',
    '        displayName: biz-ai-agent base model',
    `        apiKeyEnv: ${env}`,
    '        api: openai-completions',
    `        baseURL: ${baseURL}`,
    '        models:',
    `          - id: ${base.model}`,
    `            name: ${base.model}`,
    '- id: agent-default-model',
    '  config:',
    '    provider: biz-ai-agent',
    `    model: ${base.model}`,
    '',
  ].join('\n')
}
