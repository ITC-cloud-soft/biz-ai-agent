export function translator(lang: Lang) {
  const d = DICTS[lang] ?? ja
  return (key: Key, vars: Record<string, string | number> = {}): string =>
    String(d[key] ?? ja[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`))
}

