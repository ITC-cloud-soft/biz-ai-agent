export type StringKey = keyof typeof STRINGS_JA
export type Strings = Readonly<Record<StringKey, string>>
export type StringOverrides = Partial<Record<StringKey, string>>

/** The default strings with overrides applied (unknown keys are ignored). */
export function createStrings(overrides: StringOverrides = {}): Strings {
  const out: Record<string, string> = { ...STRINGS_JA }
  for (const [k, v] of Object.entries(overrides)) if (k in STRINGS_JA && typeof v === 'string') out[k] = v
  return Object.freeze(out) as Strings
}

/** Fills {name} placeholders. */
export function format(template: string, vars: Readonly<Record<string, string | number>> = {}): string {
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (all, name: string) => (name in vars ? String(vars[name]) : all))
}

/** t(strings, key, vars) */
export const t = (strings: Strings, key: StringKey, vars?: Readonly<Record<string, string | number>>): string => format(strings[key] ?? STRINGS_JA[key], vars)

/** A rich template split into text, {name} placeholders and **bold** spans (no nesting of bold). */
export type RichToken = { kind: 'text'; text: string } | { kind: 'var'; name: string } | { kind: 'bold'; children: RichToken[] }

function placeholders(text: string): RichToken[] {
  const out: RichToken[] = []
  let last = 0
  for (const m of text.matchAll(/\{([A-Za-z0-9_]+)\}/g)) {
    if (m.index > last) out.push({ kind: 'text', text: text.slice(last, m.index) })
    out.push({ kind: 'var', name: m[1] })
    last = m.index + m[0].length
  }
  if (last < text.length) out.push({ kind: 'text', text: text.slice(last) })
  return out
}

/** parseRich('a **{x}** b') -> text 'a ', bold [var x], text ' b'. An unmatched ** stays as text. */
export function parseRich(template: string): RichToken[] {
  const parts = template.split('**')
  if (parts.length % 2 === 0) parts.splice(parts.length - 2, 2, `${parts[parts.length - 2]}**${parts[parts.length - 1]}`)
  const out: RichToken[] = []
  parts.forEach((part, i) => {
    if (i % 2 === 1) out.push({ kind: 'bold', children: placeholders(part) })
    else out.push(...placeholders(part))
  })
  return out
}
